%% PropSimWorking.m
% Plain-MATLAB time-stepping version of propulsion.slx.
%
% Pressure-loss model:
%   Oxidizer -> parallelOxPressureLoss
%   Fuel     -> branchPressureLoss
%
% Current assumption:
%   Darcy friction factor f = 0.04 for both oxidizer and fuel.
%   Therefore viscosity is NOT required for this version.

clear;
clc;
close all;


%% ---------------- Settings ----------------------------------------------

dt   = 0.01;     % [s]
tEnd = 10;       % [s]

% 'energy'    -> P_ox from internal energy + density
% 'saturated' -> P_ox from saturation pressure at T_ox
P_ox_model = 'energy';


%% ---------------- Constants / initial conditions ------------------------

T_amb      = 300;       % [K]
rho_f      = 794;       % [kg/m^3]
m_ox0      = 33.8916;   % [kg]
m_f0       = 9.678;     % [kg]

fric_power = 1;         % [W]
dP_fric    = 1;         % [Pa]


% Initial oxidizer volume
v_ox0 = m_ox0 / props( ...
    'D', ...
    'T', T_amb, ...
    'Q', 0, ...
    'N2O');


% Initial oxidizer mass / internal energy
m_ox_initial = v_ox0 * props( ...
    'D', ...
    'T', T_amb, ...
    'Q', 0, ...
    'N2O');

u_ox_initial = m_ox_initial * props( ...
    'U', ...
    'T', T_amb, ...
    'Q', 0, ...
    'N2O');


%% ---------------- Preallocate logs --------------------------------------

N = floor(tEnd / dt) + 1;

L.t        = zeros(1,N);
L.T_ox     = zeros(1,N);
L.P_ox     = zeros(1,N);
L.P_f      = zeros(1,N);

L.m_dot_ox = zeros(1,N);
L.m_dot_f  = zeros(1,N);

L.Pc       = zeros(1,N);
L.F        = zeros(1,N);
L.OF       = zeros(1,N);
L.Isp      = zeros(1,N);

L.m_ox     = zeros(1,N);
L.m_f      = zeros(1,N);


%% ---------------- States ------------------------------------------------

m_ox       = m_ox0;
m_f        = m_f0;

U_removed  = 0;
M_fuel_out = 0;


%% ---------------- Main loop ---------------------------------------------

nLogged = 0;

for k = 1:N

    t = (k - 1) * dt;

    try

        %% ---- Thermodynamic state ---------------------------------------

        v_ox = v_ox0 + M_fuel_out / rho_f;

        u_ox = u_ox_initial - U_removed;


        T_ox = props( ...
            'T', ...
            'D', m_ox / v_ox, ...
            'Q', 0, ...
            'N2O');


        rho_ox = props( ...
            'D', ...
            'T', T_ox, ...
            'Q', 0, ...
            'N2O');


        P_ox = calc_P_ox( ...
            P_ox_model, ...
            u_ox, ...
            v_ox, ...
            m_ox, ...
            T_ox);


        P_f = P_ox - dP_fric;


        % Fuel temperature is still required by the
        % energy-balance calculation below.
        T_f = props( ...
            'T', ...
            'D', rho_f, ...
            'P', P_f, ...
            'Ethanol');


        %% ---- Engine / feed-system solve --------------------------------

        [m_dot_ox, m_dot_f, Pc, F, OF, Isp] = ...
            engine_solver( ...
                P_ox, ...
                P_f, ...
                rho_ox, ...
                rho_f);


        %% ---- Energy-balance terms --------------------------------------

        w_piston = ...
            (m_dot_f / props( ...
                'D', ...
                'T', T_f, ...
                'P', P_f, ...
                'Ethanol')) ...
            * props( ...
                'P', ...
                'T', T_ox, ...
                'Q', 0, ...
                'N2O');


        u_out = ...
            m_dot_ox * props( ...
                'U', ...
                'T', T_ox, ...
                'Q', 0, ...
                'N2O');


    catch err

        warning( ...
            'Stopped at t = %.3f s: %s', ...
            t, ...
            err.message);

        break

    end


    %% ---- Log -----------------------------------------------------------

    nLogged = k;

    L.t(k)        = t;

    L.T_ox(k)     = T_ox;
    L.P_ox(k)     = P_ox;
    L.P_f(k)      = P_f;

    L.m_dot_ox(k) = m_dot_ox;
    L.m_dot_f(k)  = m_dot_f;

    L.Pc(k)       = Pc;
    L.F(k)        = F;
    L.OF(k)       = OF;
    L.Isp(k)      = Isp;

    L.m_ox(k)     = m_ox;
    L.m_f(k)      = m_f;


    %% ---- State update --------------------------------------------------

    U_removed = ...
        U_removed ...
        + dt * (w_piston + fric_power + u_out);


    M_fuel_out = ...
        M_fuel_out ...
        + dt * m_dot_f;


    m_ox = ...
        m_ox ...
        - dt * m_dot_ox;


    m_f = ...
        m_f ...
        - dt * m_dot_f;


    %% Stop if either tank empties

    if m_ox <= 0 || m_f <= 0

        warning( ...
            'A propellant tank emptied at t = %.3f s - stopping.', ...
            t + dt);

        break

    end

end


%% ---------------- Trim unused samples ----------------------------------

for fn = fieldnames(L)'

    L.(fn{1}) = ...
        L.(fn{1})(1:nLogged);

end


