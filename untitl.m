%% =======================================================================
%% Local functions
%% =======================================================================


function scopePlot(tl, t, y, ttl, ylab)

    nexttile(tl);

    plot( ...
        t, ...
        y, ...
        'LineWidth', ...
        1.5);

    grid on;

    title(ttl);

    xlabel('Time [s]');

    ylabel(ylab);

end


function y = props(varargin)

    % CoolProp wrapper
    y = double( ...
        py.CoolProp.CoolProp.PropsSI(varargin{:}));

end


function P_ox = calc_P_ox( ...
    model, ...
    u_ox, ...
    v_ox, ...
    m_ox, ...
    T_ox)


    switch model

        case 'energy'

            P_ox = props( ...
                'P', ...
                'Umass', u_ox / m_ox, ...
                'Dmass', m_ox / v_ox, ...
                'N2O');


        case 'saturated'

            P_ox = props( ...
                'P', ...
                'T', T_ox, ...
                'Q', 0, ...
                'N2O');


        otherwise

            error( ...
                'Unknown P_ox_model "%s".', ...
                model);

    end

end


function [m_dot_ox, m_dot_f, Pc, F, O_F, Isp] = ...
    engine_solver( ...
        P_ox, ...
        P_f, ...
        rho_ox, ...
        rho_f)


    %% Engine constants

    g0 = 9.81;               % [m/s^2]

    c_star = 2639.4;         % [m/s]

    A_t = 7.85398e-5;        % [m^2]

    A_e = 1.8816e-3;         % [m^2]

    C_f = A_e / A_t;         % retained from original model


    %% Initial guess
    % [mdot_ox; mdot_f; Pc]

    x0 = [ ...
        1.66337; ...
        0.478249; ...
        435.113 * 6894.76];


    %% fsolve options

    options = optimoptions( ...
        'fsolve', ...
        'Algorithm', 'levenberg-marquardt', ...
        'Display', 'off', ...
        'FunctionTolerance', 1e-6);


    %% Solve

    [x_sol, ~, exitflag] = fsolve( ...
        @(x) engine_residuals( ...
            x, ...
            P_ox, ...
            P_f, ...
            rho_ox, ...
            rho_f, ...
            A_t, ...
            c_star), ...
        x0, ...
        options);


    %% Fallback if solver fails

    if exitflag <= 0

        warning( ...
            'engine_solver:fsolve', ...
            ['fsolve did not converge. ' ...
             'Using initial guess for this timestep.']);

        x_sol = x0;

    end


    %% Outputs

    m_dot_ox = abs(x_sol(1));

    m_dot_f = abs(x_sol(2));

    Pc = abs(x_sol(3));


    m_dot_tot = ...
        m_dot_ox + m_dot_f;


    F = ...
        C_f * Pc * A_t;


    O_F = ...
        m_dot_ox / max(m_dot_f, 1e-6);


    Isp = ...
        F / ...
        (max(m_dot_tot, 1e-6) * g0);

end


function R = engine_residuals( ...
    x, ...
    P_ox, ...
    P_f, ...
    rho_ox, ...
    rho_f, ...
    A_t, ...
    c_star)


    %% Solver guesses

    m_dot_ox_guess = ...
        abs(x(1));

    m_dot_f_guess = ...
        abs(x(2));

    Pc_guess = ...
        abs(x(3));


    %% Vehicle geometry

    geom = vehicleGeometry();


    %% Current pressure-loss assumptions

    fFixed = 0.04;
    % Assumed Darcy friction factor


    roughness = 0;
    % Not used while fixed friction factor is supplied


    Cd = 1.0;
    % Matches the old injector equation for now


    dz = 0.9144;
    % [m] existing model value


    %% ---------------------------------------------------------------
    %% Oxidizer
    %% Two identical parallel branches
    %% ---------------------------------------------------------------

    ox = parallelOxPressureLoss( ...
        m_dot_ox_guess, ...
        rho_ox, ...
        NaN, ...                  % viscosity not needed
        geom.oxLeft.L, ...
        geom.oxLeft.D, ...
        roughness, ...
        10, ...                   % K
        9, ...                    % Cv
        Cd, ...
        2.20893e-5, ...           % total OX injector area [m^2]
        dz, ...
        fFixed=fFixed);


    dp_ox = ...
        ox.dP_total;


    %% ---------------------------------------------------------------
    %% Fuel
    %% One branch
    %% ---------------------------------------------------------------

    fuel = branchPressureLoss( ...
        m_dot_f_guess, ...
        rho_f, ...
        NaN, ...                  % viscosity not needed
        geom.fuel.L, ...
        geom.fuel.D, ...
        roughness, ...
        10, ...                   % K
        5.228, ...                % Cv
        Cd, ...
        1.8816e-3, ...            % injector area [m^2]
        dz, ...
        fFixed=fFixed);


    dp_f = ...
        fuel.dP_total;


    %% ---------------------------------------------------------------
    %% Residual equations
    %% ---------------------------------------------------------------

    R_ox = ...
        P_ox ...
        - dp_ox ...
        - Pc_guess;


    R_f = ...
        P_f ...
        - dp_f ...
        - Pc_guess;


    R_c = ...
        (m_dot_ox_guess + m_dot_f_guess) ...
        - (Pc_guess * A_t / c_star);


    R = [ ...
        R_ox; ...
        R_f; ...
        R_c];


    %% Protect fsolve from invalid values

    if any(~isfinite(R))

        R = [ ...
            1e6; ...
            1e6; ...
            1e6];

    end

end